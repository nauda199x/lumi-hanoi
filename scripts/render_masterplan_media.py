def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('brochure', type=Path)
    parser.add_argument('--work-dir', type=Path, required=True)
    parser.add_argument('--font-dir', type=Path,
                        default=Path('/usr/share/fonts/truetype/dejavu'))
    args = parser.parse_args()
    args.work_dir.mkdir(parents=True, exist_ok=True)
    pdfmetrics.registerFont(TTFont('Plan', str(args.font_dir / 'DejaVuSans.ttf')))
    pdfmetrics.registerFont(TTFont('PlanBold', str(args.font_dir / 'DejaVuSans-Bold.ttf')))
    records = SOLE_OUTDOOR + SOLE_INDOOR + LUNA_OUTDOOR + LUNA_INDOOR + GREEN + SPORTS
    assert {number for number, _ in records} == set(range(1, 81))
    assert len(records) == 86  # Six indoor facilities reuse the original plan's numbers.

    source = fitz.open(args.brochure)
    page = source[6]
    pix = page.get_pixmap(matrix=fitz.Matrix(3840 / page.rect.width,
                                           3840 / page.rect.width), alpha=False)
    original = Image.frombytes('RGB', (pix.width, pix.height), pix.samples)
    # Crop the artwork from the spread; preserve every tower and facility marker.
    artwork = original.crop((0, 430, 2180, 2220))
    paper = '#%02x%02x%02x' % original.getpixel((20, 20))
    pdf = args.work_dir / 'masterplan-layout.pdf'
    c = canvas.Canvas(str(pdf), pagesize=(3840, 2560))
    c.setTitle('Mặt bằng cảnh quan Lumi Signature - chú giải tiếng Việt')
    c.setAuthor('Lumi Hanoi')
    c.setFillColor(HexColor(paper))
    c.rect(0, 0, 3840, 2560, fill=1, stroke=0)

    def text(x, y, value, size=24, bold=False, color='#293e34'):
        c.setFillColor(HexColor(color))
        c.setFont('PlanBold' if bold else 'Plan', size)
        c.drawString(x, 2560 - y, value)

    def wrap(value, width=680):
        lines, line = [], ''
        for word in value.split():
            candidate = f'{line} {word}'.strip()
            if line and pdfmetrics.stringWidth(candidate, 'Plan', 24) > width:
                lines.append(line)
                line = word
            else:
                line = candidate
        return lines + [line]

    def entries(x, y, records, color, indoor=False):
        for number, label in records:
            cy = 2560 - y + 8
            c.setFillColor(HexColor(color))
            if indoor:
                path = c.beginPath()
                path.moveTo(x + 18, cy + 21)
                path.lineTo(x + 39, cy)
                path.lineTo(x + 18, cy - 21)
                path.lineTo(x - 3, cy)
                path.close()
                c.drawPath(path, fill=1, stroke=0)
            else:
                c.circle(x + 18, cy, 19, fill=1, stroke=0)
            c.setFillColor(HexColor('#3a403a'))
            c.setFont('PlanBold', 19)
            c.drawCentredString(x + 18, cy - 6.5, str(number))
            lines = wrap(label)
            for line in lines:
                text(x + 52, y, line)
                y += 31
            y += 10
        return y

    def heading(x, y, value, color):
        c.setFillColor(HexColor(color))
        c.roundRect(x - 8, 2560 - y - 19, 758, 67, 12, fill=1, stroke=0)
        text(x + 16, y + 2, value, 32, True)
        return y + 75

    text(82, 112, 'LUMI HANOI', 30, True)
    text(80, 221, 'Mặt bằng cảnh quan', 69, True)
    text(80, 307, 'Lumi Signature', 69, True)
    text(84, 373, 'S1  ·  S2  ·  S3  ·  S5  ·  S6', 31, color='#766752')
    c.drawImage(ImageReader(artwork), 35, 2560 - 440 - 1790 * 2140 / 2180,
                width=2140, height=1790 * 2140 / 2180, mask='auto')
    text(85, 2300, 'SOLE ZONE', 28, True)
    text(85, 2352, 'S1 · S2 · S3', 27)
    text(720, 2300, 'LUNA ZONE', 28, True)
    text(720, 2352, 'S5 · S6', 27)
    text(1330, 2300, 'CHÚ GIẢI', 28, True)
    text(1330, 2352, 'Số trên sơ đồ ↔ tên tiện ích', 27)
    c.setStrokeColor(HexColor('#d5d1c6'))
    c.setLineWidth(2)
    c.line(2185, 160, 2185, 2460)
    text(2230, 95, 'CHÚ GIẢI TIỆN ÍCH', 26, True)
    left = heading(2230, 164, 'SOLE ZONE', '#e7d7bd')
    text(2230, left, 'Ngoài trời', 25, True)
    left = entries(2230, left + 45, SOLE_OUTDOOR, '#e7d7bd')
    text(2230, left + 14, 'Trong nhà', 25, True)
    left = entries(2230, left + 59, SOLE_INDOOR, '#e7d7bd', True)
    left = heading(2230, left + 45, 'LÁ PHỔI XANH', '#d1dbc4')
    left = entries(2230, left, GREEN, '#d1dbc4')
    right = heading(3030, 164, 'LUNA ZONE', '#dcd3e8')
    text(3030, right, 'Ngoài trời', 25, True)
    right = entries(3030, right + 45, LUNA_OUTDOOR, '#dcd3e8')
    text(3030, right + 14, 'Trong nhà', 25, True)
    right = entries(3030, right + 59, LUNA_INDOOR, '#dcd3e8', True)
    right = heading(3030, right + 45, 'THỂ THAO', '#e5dfcf')
    right = entries(3030, right, SPORTS, '#e5dfcf')
    print('Legend bottom:', left, right)
    assert max(left, right) < 2440, 'Legend would overlap the footer'
    c.setStrokeColor(HexColor('#d5d1c6'))
    c.line(82, 116, 3760, 116)
    text(82, 2490, 'Sơ đồ cảnh quan và tiện ích phân khu Signature; vị trí mang tính tương đối.',
         24, color='#66665d')
    text(3480, 2490, 'lumi-hanoi.com', 24, True)
    c.showPage()
    c.save()

    rendered = fitz.open(pdf)
    assert 'Sân tập golf mini' in rendered[0].get_text()
    pix = rendered[0].get_pixmap(alpha=False)
    image = Image.frombytes('RGB', (pix.width, pix.height), pix.samples)
    image.save(args.work_dir / 'masterplan-layout-3840.png')
    target_dir = ROOT / 'assets/media/masterplan'
    for width, quality in [(640, 80), (1280, 82), (1920, 78), (3840, 90)]:
        variant = image if width == 3840 else image.resize(
            (width, round(width * 2560 / 3840)), Image.Resampling.LANCZOS)
        target = target_dir / f'lumi-hanoi-masterplan-{width}.webp'
        variant.save(target, 'WEBP', quality=quality, method=6)
        if width == 1280:
            # Keep historical image URLs useful without serving 4K on page load.
            (target_dir / 'lumi-hanoi-masterplan.webp').write_bytes(target.read_bytes())
        print(target.name, variant.size, target.stat().st_size)


if __name__ == '__main__':
    main()
