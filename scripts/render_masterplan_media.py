#!/usr/bin/env python3
"""Render an exact, legible Signature facilities legend alongside the original plan.

Input: page 7 (printed pages 11–12) of CapitaLand's public Main Brochure:
https://www.capitaland.com/sites/lumihanoi/resources/wp-content/uploads/2024/07/Capitaland-Lumi-Main-Brochure.pdf
The landscape artwork is preserved. Vietnamese legend text is typeset again;
no buildings, facilities, marker positions, or dimensions are generated by AI.
"""
